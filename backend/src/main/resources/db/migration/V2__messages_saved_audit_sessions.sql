
-- 1. Forwarded messages
ALTER TABLE public.messages
    ADD COLUMN IF NOT EXISTS forwarded_from_id BIGINT,
    ADD COLUMN IF NOT EXISTS forwarded_from_name VARCHAR(100);

-- 2. Group announcement mode
ALTER TABLE public.conversations
    ADD COLUMN IF NOT EXISTS announcement_only BOOLEAN NOT NULL DEFAULT FALSE;

-- 3. Saved messages
CREATE TABLE IF NOT EXISTS public.saved_messages (
                                                     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                     user_id BIGINT NOT NULL,
                                                     message_id BIGINT NOT NULL,
                                                     created_at TIMESTAMP(3) WITH TIME ZONE NOT NULL,
                                                                                 CONSTRAINT uq_saved UNIQUE (user_id, message_id),
    CONSTRAINT fk_saved_user
    FOREIGN KEY (user_id) REFERENCES public.users(id),
    CONSTRAINT fk_saved_msg
    FOREIGN KEY (message_id)
    REFERENCES public.messages(id) ON DELETE CASCADE
    );

CREATE INDEX IF NOT EXISTS idx_saved_user
    ON public.saved_messages(user_id, id);

-- 4. Hidden messages
CREATE TABLE IF NOT EXISTS public.hidden_messages (
                                                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                      user_id BIGINT NOT NULL,
                                                      message_id BIGINT NOT NULL,
                                                      created_at TIMESTAMP(3) WITH TIME ZONE NOT NULL,
                                                                                  CONSTRAINT uq_hidden UNIQUE (user_id, message_id),
    CONSTRAINT fk_hidden_user
    FOREIGN KEY (user_id) REFERENCES public.users(id),
    CONSTRAINT fk_hidden_msg
    FOREIGN KEY (message_id)
    REFERENCES public.messages(id) ON DELETE CASCADE
    );

-- 5. Group audit events
CREATE TABLE IF NOT EXISTS public.group_audit_events (
                                                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                         conversation_id BIGINT NOT NULL,
                                                         actor_id BIGINT NOT NULL,
                                                         action VARCHAR(40) NOT NULL,
    target_id BIGINT,
    detail VARCHAR(255),
    created_at TIMESTAMP(3) WITH TIME ZONE NOT NULL,
                                CONSTRAINT fk_audit_conv
                                FOREIGN KEY (conversation_id)
    REFERENCES public.conversations(id) ON DELETE CASCADE
    );

CREATE INDEX IF NOT EXISTS idx_audit_conv
    ON public.group_audit_events(conversation_id, id);

-- 6. User sessions / device management
CREATE TABLE IF NOT EXISTS public.user_sessions (
                                                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                    session_id CHAR(36) NOT NULL,
    user_id BIGINT NOT NULL,
    user_agent VARCHAR(255),
    ip VARCHAR(45),
    created_at TIMESTAMP(3) WITH TIME ZONE NOT NULL,
                                last_seen_at TIMESTAMP(3) WITH TIME ZONE NOT NULL,
                                expires_at TIMESTAMP(3) WITH TIME ZONE NOT NULL,
                                revoked BOOLEAN NOT NULL DEFAULT FALSE,
                                CONSTRAINT uq_session_id UNIQUE (session_id),
    CONSTRAINT fk_session_user
    FOREIGN KEY (user_id) REFERENCES public.users(id)
    );

CREATE INDEX IF NOT EXISTS idx_session_user
    ON public.user_sessions(user_id);
