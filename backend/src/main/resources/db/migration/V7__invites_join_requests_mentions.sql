
-- 1. Group invitation links
CREATE TABLE IF NOT EXISTS public.group_invites (
                                                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                    conversation_id BIGINT NOT NULL,
                                                    token_hash CHAR(64) NOT NULL,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMP(3) WITH TIME ZONE NOT NULL,
                                expires_at TIMESTAMP(3) WITH TIME ZONE,
                                max_uses INTEGER,
                                use_count INTEGER NOT NULL DEFAULT 0,
                                revoked BOOLEAN NOT NULL DEFAULT FALSE,
                                requires_approval BOOLEAN NOT NULL DEFAULT FALSE,

                                CONSTRAINT uq_invite_token UNIQUE (token_hash),
    CONSTRAINT fk_invite_conv
    FOREIGN KEY (conversation_id)
    REFERENCES public.conversations(id) ON DELETE CASCADE,
    CONSTRAINT fk_invite_user
    FOREIGN KEY (created_by)
    REFERENCES public.users(id)
    );

CREATE INDEX IF NOT EXISTS idx_invite_conv
    ON public.group_invites(conversation_id, id);


-- 2. Group join requests
CREATE TABLE IF NOT EXISTS public.join_requests (
                                                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                    conversation_id BIGINT NOT NULL,
                                                    user_id BIGINT NOT NULL,
                                                    invite_id BIGINT,
                                                    status VARCHAR(10) NOT NULL,
    pending_key SMALLINT,
    created_at TIMESTAMP(3) WITH TIME ZONE NOT NULL,
                                decided_by BIGINT,
                                decided_at TIMESTAMP(3) WITH TIME ZONE,

                                CONSTRAINT uq_join_pending
                                UNIQUE (conversation_id, user_id, pending_key),
    CONSTRAINT fk_join_conv
    FOREIGN KEY (conversation_id)
    REFERENCES public.conversations(id) ON DELETE CASCADE,
    CONSTRAINT fk_join_user
    FOREIGN KEY (user_id)
    REFERENCES public.users(id)
    );

CREATE INDEX IF NOT EXISTS idx_join_conv_status
    ON public.join_requests(conversation_id, status);


-- 3. Message @mentions
CREATE TABLE IF NOT EXISTS public.message_mentions (
                                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                       message_id BIGINT NOT NULL,
                                                       user_id BIGINT NOT NULL,
                                                       name_at_send VARCHAR(100) NOT NULL,

    CONSTRAINT uq_mention UNIQUE (message_id, user_id),
    CONSTRAINT fk_mention_msg
    FOREIGN KEY (message_id)
    REFERENCES public.messages(id) ON DELETE CASCADE,
    CONSTRAINT fk_mention_user
    FOREIGN KEY (user_id)
    REFERENCES public.users(id)
    );

CREATE INDEX IF NOT EXISTS idx_mention_user
    ON public.message_mentions(user_id, message_id);
