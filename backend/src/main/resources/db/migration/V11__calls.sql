
-- 1. Create calls table
CREATE TABLE IF NOT EXISTS public.calls (
                                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                            call_uid CHAR(36) NOT NULL,
    conversation_id BIGINT NOT NULL,
    caller_id BIGINT NOT NULL,
    callee_id BIGINT NOT NULL,
    type VARCHAR(5) NOT NULL,
    status VARCHAR(10) NOT NULL,
    started_at TIMESTAMP(3) WITH TIME ZONE NOT NULL,
                                answered_at TIMESTAMP(3) WITH TIME ZONE,
                                ended_at TIMESTAMP(3) WITH TIME ZONE,
                                duration_seconds INTEGER,
                                end_reason VARCHAR(20),
    callee_seen BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT uq_call_uid UNIQUE (call_uid),

    CONSTRAINT fk_call_conv
    FOREIGN KEY (conversation_id)
    REFERENCES public.conversations(id) ON DELETE CASCADE,

    CONSTRAINT fk_call_caller
    FOREIGN KEY (caller_id)
    REFERENCES public.users(id),

    CONSTRAINT fk_call_callee
    FOREIGN KEY (callee_id)
    REFERENCES public.users(id)
    );

CREATE INDEX IF NOT EXISTS idx_call_caller
    ON public.calls(caller_id, id);

CREATE INDEX IF NOT EXISTS idx_call_callee
    ON public.calls(callee_id, id);


-- 2. Add calls notification preference
ALTER TABLE public.notification_prefs
    ADD COLUMN IF NOT EXISTS calls BOOLEAN NOT NULL DEFAULT TRUE;
