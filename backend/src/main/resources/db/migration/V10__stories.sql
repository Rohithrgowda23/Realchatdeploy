
-- 1. Stories
CREATE TABLE IF NOT EXISTS public.stories (
                                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                              author_id BIGINT NOT NULL,
                                              type VARCHAR(10) NOT NULL,
    text VARCHAR(500),
    bg_color VARCHAR(7),
    stored_name CHAR(36),
    mime_type VARCHAR(100),
    size_bytes BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(3) WITH TIME ZONE NOT NULL,
                                expires_at TIMESTAMP(3) WITH TIME ZONE NOT NULL,

                                CONSTRAINT fk_story_author
                                FOREIGN KEY (author_id)
    REFERENCES public.users(id) ON DELETE CASCADE
    );

CREATE INDEX IF NOT EXISTS idx_story_author
    ON public.stories(author_id, expires_at);

CREATE INDEX IF NOT EXISTS idx_story_expiry
    ON public.stories(expires_at);


-- 2. Story views
CREATE TABLE IF NOT EXISTS public.story_views (
                                                  story_id BIGINT NOT NULL,
                                                  viewer_id BIGINT NOT NULL,
                                                  viewed_at TIMESTAMP(3) WITH TIME ZONE NOT NULL,

                                                                             CONSTRAINT pk_story_views
                                                                             PRIMARY KEY (story_id, viewer_id),

    CONSTRAINT fk_view_story
    FOREIGN KEY (story_id)
    REFERENCES public.stories(id) ON DELETE CASCADE,

    CONSTRAINT fk_view_user
    FOREIGN KEY (viewer_id)
    REFERENCES public.users(id) ON DELETE CASCADE
    );


-- 3. Story privacy settings
CREATE TABLE IF NOT EXISTS public.story_settings (
                                                     user_id BIGINT PRIMARY KEY,
                                                     audience VARCHAR(20) NOT NULL DEFAULT 'CONTACTS',

    CONSTRAINT fk_story_settings_user
    FOREIGN KEY (user_id)
    REFERENCES public.users(id) ON DELETE CASCADE
    );


-- 4. Hidden stories/users
CREATE TABLE IF NOT EXISTS public.story_hidden (
                                                   id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                   user_id BIGINT NOT NULL,
                                                   hidden_user_id BIGINT NOT NULL,

                                                   CONSTRAINT uq_story_hidden
                                                   UNIQUE (user_id, hidden_user_id),

    CONSTRAINT fk_hidden_owner
    FOREIGN KEY (user_id)
    REFERENCES public.users(id) ON DELETE CASCADE,

    CONSTRAINT fk_hidden_target
    FOREIGN KEY (hidden_user_id)
    REFERENCES public.users(id) ON DELETE CASCADE
    );
