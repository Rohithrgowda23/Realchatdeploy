
-- 1. Delivered receipts
ALTER TABLE public.conversation_members
    ADD COLUMN IF NOT EXISTS last_delivered_message_id BIGINT
    NOT NULL DEFAULT 0;

UPDATE public.conversation_members
SET last_delivered_message_id = last_read_message_id
WHERE last_delivered_message_id < last_read_message_id;


-- 2. Scheduled messages
CREATE TABLE IF NOT EXISTS public.scheduled_messages (
                                                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                         conversation_id BIGINT NOT NULL,
                                                         sender_id BIGINT NOT NULL,
                                                         content TEXT NOT NULL,
                                                         reply_to_id BIGINT,
                                                         scheduled_at TIMESTAMP(3) WITH TIME ZONE NOT NULL,
                                                                                       status VARCHAR(10) NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    last_error VARCHAR(255),
    claimed_at TIMESTAMP(3) WITH TIME ZONE,
                                                                                       sent_message_id BIGINT,
                                                                                       sent_at TIMESTAMP(3) WITH TIME ZONE,
                                                                                       created_at TIMESTAMP(3) WITH TIME ZONE NOT NULL,
                                                                                       version BIGINT NOT NULL DEFAULT 0,

                                                                                       CONSTRAINT fk_sched_conv
                                                                                       FOREIGN KEY (conversation_id)
    REFERENCES public.conversations(id) ON DELETE CASCADE,
    CONSTRAINT fk_sched_sender
    FOREIGN KEY (sender_id)
    REFERENCES public.users(id)
    );

CREATE INDEX IF NOT EXISTS idx_sched_due
    ON public.scheduled_messages(status, scheduled_at);

CREATE INDEX IF NOT EXISTS idx_sched_sender
    ON public.scheduled_messages(sender_id, scheduled_at);


-- 3. Notifications
CREATE TABLE IF NOT EXISTS public.notifications (
                                                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                    user_id BIGINT NOT NULL,
                                                    type VARCHAR(30) NOT NULL,
    title VARCHAR(160) NOT NULL,
    body VARCHAR(255),
    conversation_id BIGINT,
    message_id BIGINT,
    read_at TIMESTAMP(3) WITH TIME ZONE,
                             created_at TIMESTAMP(3) WITH TIME ZONE NOT NULL,

                             CONSTRAINT fk_notif_user
                             FOREIGN KEY (user_id)
    REFERENCES public.users(id) ON DELETE CASCADE
    );

CREATE INDEX IF NOT EXISTS idx_notif_user
    ON public.notifications(user_id, id);

CREATE INDEX IF NOT EXISTS idx_notif_unread
    ON public.notifications(user_id, read_at);


-- 4. Notification preferences
CREATE TABLE IF NOT EXISTS public.notification_prefs (
                                                         user_id BIGINT PRIMARY KEY,
                                                         mentions BOOLEAN NOT NULL DEFAULT TRUE,
                                                         join_requests BOOLEAN NOT NULL DEFAULT TRUE,
                                                         scheduled BOOLEAN NOT NULL DEFAULT TRUE,

                                                         CONSTRAINT fk_prefs_user
                                                         FOREIGN KEY (user_id)
    REFERENCES public.users(id) ON DELETE CASCADE
    );
