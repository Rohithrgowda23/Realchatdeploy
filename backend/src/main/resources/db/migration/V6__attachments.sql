
CREATE TABLE IF NOT EXISTS public.attachments (
                                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                  message_id BIGINT NOT NULL,
                                                  conversation_id BIGINT NOT NULL,
                                                  kind VARCHAR(10) NOT NULL,
    original_name VARCHAR(255) NOT NULL,
    stored_name CHAR(36) NOT NULL,
    mime_type VARCHAR(100) NOT NULL,
    size_bytes BIGINT NOT NULL,
    duration_ms INTEGER,
    created_at TIMESTAMP(3) WITH TIME ZONE NOT NULL,

                                CONSTRAINT uq_attachment_message UNIQUE (message_id),
    CONSTRAINT uq_attachment_stored UNIQUE (stored_name),

    CONSTRAINT fk_attachment_message
    FOREIGN KEY (message_id)
    REFERENCES public.messages(id) ON DELETE CASCADE
    );

CREATE INDEX IF NOT EXISTS idx_attachment_gallery
    ON public.attachments(conversation_id, kind, message_id);
