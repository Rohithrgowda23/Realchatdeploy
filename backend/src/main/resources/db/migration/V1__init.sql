
CREATE TABLE IF NOT EXISTS public.users (
                                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                            name VARCHAR(100) NOT NULL,
    email VARCHAR(190) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    about VARCHAR(255),
    avatar_url VARCHAR(500),
    created_at TIMESTAMP(3) WITH TIME ZONE NOT NULL,
                                CONSTRAINT uq_users_email UNIQUE (email)
    );

CREATE TABLE IF NOT EXISTS public.conversations (
                                                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                    type VARCHAR(10) NOT NULL,
    name VARCHAR(100),
    description VARCHAR(500),
    avatar_url VARCHAR(500),
    direct_key VARCHAR(50),
    created_by BIGINT NOT NULL,
    created_at TIMESTAMP(3) WITH TIME ZONE NOT NULL,
                                CONSTRAINT uq_conv_direct_key UNIQUE (direct_key),
    CONSTRAINT fk_conv_creator
    FOREIGN KEY (created_by) REFERENCES public.users(id)
    );

CREATE TABLE IF NOT EXISTS public.conversation_members (
                                                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                           conversation_id BIGINT NOT NULL,
                                                           user_id BIGINT NOT NULL,
                                                           role VARCHAR(10) NOT NULL,
    pinned BOOLEAN NOT NULL DEFAULT FALSE,
    muted BOOLEAN NOT NULL DEFAULT FALSE,
    archived BOOLEAN NOT NULL DEFAULT FALSE,
    last_read_message_id BIGINT NOT NULL DEFAULT 0,
    joined_at TIMESTAMP(3) WITH TIME ZONE NOT NULL,
                               CONSTRAINT uq_member UNIQUE (conversation_id, user_id),
    CONSTRAINT fk_member_conv
    FOREIGN KEY (conversation_id)
    REFERENCES public.conversations(id) ON DELETE CASCADE,
    CONSTRAINT fk_member_user
    FOREIGN KEY (user_id) REFERENCES public.users(id)
    );

CREATE INDEX IF NOT EXISTS idx_member_user
    ON public.conversation_members(user_id);

CREATE TABLE IF NOT EXISTS public.messages (
                                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                               conversation_id BIGINT NOT NULL,
                                               sender_id BIGINT NOT NULL,
                                               content TEXT,
                                               reply_to_id BIGINT,
                                               edited BOOLEAN NOT NULL DEFAULT FALSE,
                                               deleted BOOLEAN NOT NULL DEFAULT FALSE,
                                               created_at TIMESTAMP(3) WITH TIME ZONE NOT NULL,
                                                                           CONSTRAINT fk_msg_conv
                                                                           FOREIGN KEY (conversation_id)
    REFERENCES public.conversations(id) ON DELETE CASCADE,
    CONSTRAINT fk_msg_sender
    FOREIGN KEY (sender_id) REFERENCES public.users(id)
    );

CREATE INDEX IF NOT EXISTS idx_msg_conv_id
    ON public.messages(conversation_id, id);

CREATE TABLE IF NOT EXISTS public.message_reactions (
                                                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                        message_id BIGINT NOT NULL,
                                                        user_id BIGINT NOT NULL,
                                                        emoji VARCHAR(16) NOT NULL,
    CONSTRAINT uq_reaction UNIQUE (message_id, user_id, emoji),
    CONSTRAINT fk_react_msg
    FOREIGN KEY (message_id)
    REFERENCES public.messages(id) ON DELETE CASCADE,
    CONSTRAINT fk_react_user
    FOREIGN KEY (user_id) REFERENCES public.users(id)
    );

CREATE TABLE IF NOT EXISTS public.user_blocks (
                                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                  blocker_id BIGINT NOT NULL,
                                                  blocked_id BIGINT NOT NULL,
                                                  created_at TIMESTAMP(3) WITH TIME ZONE NOT NULL,
                                                                              CONSTRAINT uq_block UNIQUE (blocker_id, blocked_id),
    CONSTRAINT fk_block_a
    FOREIGN KEY (blocker_id) REFERENCES public.users(id),
    CONSTRAINT fk_block_b
    FOREIGN KEY (blocked_id) REFERENCES public.users(id)
    );
